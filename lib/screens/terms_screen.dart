  static List<_PolicyBlock> _parseBlocks(String source) {
    final blocks = <_PolicyBlock>[];
    var previousLineWasEmpty = false;

    for (final rawLine in source.split('\n')) {
      final line = rawLine.trim();
      if (line.isEmpty) {
        previousLineWasEmpty = true;
        continue;
      }
      if (line == '---') {
        previousLineWasEmpty = true;
        continue;
      }

      final spacing = previousLineWasEmpty ? 12.0 : 2.0;
      previousLineWasEmpty = false;

      if (line.startsWith('# ')) {
        blocks.add(
          _PolicyBlock(
            text: line.substring(2),
            style: _titleStyle,
            spacingBefore: blocks.isEmpty ? 0 : 20,
          ),
        );
      } else if (line.startsWith('## ')) {
        blocks.add(
          _PolicyBlock(
            text: line.substring(3),
            style: _headingStyle,
            spacingBefore: blocks.isEmpty ? 0 : 20,
          ),
        );
      } else if (line.startsWith('### ')) {
        blocks.add(
          _PolicyBlock(
            text: line.substring(4),
            style: _subheadingStyle,
            spacingBefore: 12,
          ),
        );
      } else if (line.startsWith('**') && line.endsWith('**')) {
        blocks.add(
          _PolicyBlock(
            text: line.substring(2, line.length - 2),
            style: _subheadingStyle,
            spacingBefore: spacing,
          ),
        );
      } else if (line.startsWith('* ')) {
        blocks.add(
          _PolicyBlock(
            text: '• ${line.substring(2).replaceAll('**', '')}',
            style: _bodyStyle,
            spacingBefore: 0,
            isBullet: true,
          ),
        );
      } else {
        blocks.add(
          _PolicyBlock(
            text: line.replaceAll('**', ''),
            style: _bodyStyle,
            spacingBefore: spacing,
          ),
        );
      }
    }

    return blocks;
  }
}

class _PolicyBlock {
  const _PolicyBlock({
    required this.text,
    required this.style,
    required this.spacingBefore,
    this.isBullet = false,
  });

  final String text;
  final TextStyle style;
  final double spacingBefore;
  final bool isBullet;
}
