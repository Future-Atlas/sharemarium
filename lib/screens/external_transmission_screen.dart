  static List<_DisclosureBlock> _parseBlocks(String source) {
    final blocks = <_DisclosureBlock>[];
    var previousLineWasEmpty = false;

    for (final rawLine in source.split('\n')) {
      final line = rawLine.trim();
      if (line.isEmpty) {
        previousLineWasEmpty = true;
        continue;
      }
      if (line == '---') {
        previousLineWasEmpty = true;
        continue;
      }

      final spacing = previousLineWasEmpty ? 10.0 : 2.0;
      previousLineWasEmpty = false;

      if (line.startsWith('# ')) {
        blocks.add(
          _DisclosureBlock(
            text: line.substring(2),
            style: _titleStyle,
            spacingBefore: blocks.isEmpty ? 0 : 20,
          ),
        );
      } else if (line.startsWith('## ')) {
        blocks.add(
          _DisclosureBlock(
            text: line.substring(3),
            style: _headingStyle,
            spacingBefore: blocks.isEmpty ? 0 : 20,
          ),
        );
      } else if (line.startsWith('### ')) {
        blocks.add(
          _DisclosureBlock(
            text: line.substring(4),
            style: _subheadingStyle,
            spacingBefore: 12,
          ),
        );
      } else if (line.startsWith('#### ')) {
        blocks.add(
          _DisclosureBlock(
            text: line.substring(5),
            style: _minorHeadingStyle,
            spacingBefore: 10,
            leftPadding: 8,
          ),
        );
      } else if (line.startsWith('**') && line.endsWith('**')) {
        blocks.add(
          _DisclosureBlock(
            text: line.substring(2, line.length - 2),
            style: _subheadingStyle,
            spacingBefore: spacing,
          ),
        );
      } else if (line.startsWith('* ')) {
        blocks.add(
          _DisclosureBlock(
            text: '• ${line.substring(2).replaceAll('**', '')}',
            style: _bodyStyle,
            spacingBefore: 0,
            leftPadding: 12,
          ),
        );
      } else {
        blocks.add(
          _DisclosureBlock(
            text: line.replaceAll('**', ''),
            style: _bodyStyle,
            spacingBefore: spacing,
          ),
        );
      }
    }

    return blocks;
  }
